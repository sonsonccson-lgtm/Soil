function buildSieves(
  retainedMap: Record<string, number>,
  passingMap: Record<string, number>,
): SieveRowInput[] {
  const baseEmptyWeights: Record<string, number> = {
    s3in: 680,
    s2in: 645,
    s1_5in: 620,
    s1in: 590,
    s3_4in: 565,
    s3_8in: 540,
    s4: 515,
    s10: 485,
    s20: 460,
    s40: 440,
    s60: 420,
    s100: 405,
    s200: 390,
  };
  return STANDARD_SIEVES.map((s) => {
    const ret = retainedMap[s.id] ?? 0;
    const empty = baseEmptyWeights[s.id] ?? 450;
    return {
      ...s,
      emptySieveG: empty,
      sievePlusSoilG: Number((empty + ret).toFixed(2)),
      massRetainedG: ret,
      directPercentPassing: passingMap[s.id] ?? 100,
    };
  });
}

